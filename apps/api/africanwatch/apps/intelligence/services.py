def _obs_hash(title: str, content: str, url: str) -> str:
    material = f"{title}\n{content}\n{url}".encode("utf-8", "ignore")
    return hashlib.sha256(material).hexdigest()


@transaction.atomic
def save_observation(
    run,
    source,
    title,
    content,
    url="",
    published_at=None,
    raw=None,
    provider_label=None,
    acquisition_method="passive_collection",
):
    """Upsert an analytical observation and append a trace for this acquisition.

    A configured CollectionSource is attached only when it actually supplied the
    observation. Built-in collectors and enrichment providers are represented by
    their own provider label, never by an unrelated fallback source.
    """
    captured_at = timezone.now()
    source_reliability = float(source.reliability) if source is not None else 0.5
    source_label = source.name if source is not None else (provider_label or "Internal collector")
    classification = classify_text(content)
    iocs = extract_iocs(content)
    grade, confidence = reliability_grade(source_reliability, 0, published_at)
    actionability = min(
        1.0,
        0.55 * classification["relevance"]
        + 0.35 * confidence
        + 0.10 * (1.0 if iocs else 0.0),
    )
    fingerprint = _obs_hash(title, content, url)
    acquisition_provenance = {
        "collector": "AfricaWatch/6.0",
        "provider": source_label,
        "retrieved_at": captured_at.isoformat(),
        "acquisition_method": acquisition_method,
        "raw": raw or {},
    }

    observation, created = IntelligenceObservation.objects.get_or_create(
        organization=run.organization,
        content_sha256=fingerprint,
        source_url=url,
        defaults={
            "run": run,
            "source": source,
            "source_label": source_label,
            "title": title[:500],
            "content": content[:10000],
            "language": classification["language"],
            "published_at": published_at,
            "retrieved_at": captured_at,
            "source_reliability": source_reliability,
            "confidence": confidence,
            "relevance": classification["relevance"],
            "actionability_score": actionability,
            "classification": classification,
            "entities": {},
            "iocs": iocs,
            "evidence_grade": grade,
            "provenance": acquisition_provenance,
        },
    )
    if not created:
        # A repeat retrieval updates freshness only. It is not independent
        # corroboration; the new acquisition is captured separately below.
        observation.last_seen = captured_at
        observation.save(update_fields=["last_seen", "updated_at"])

    record_observation_evidence(
        observation,
        run=run,
        source=source,
        source_label=source_label,
        source_url=url,
        acquisition_method=acquisition_method,
        acquisition_provenance=acquisition_provenance,
        captured_at=captured_at,
    )
    return observation, created


def run_collection(run_id: str) -> dict:
    run = (
        CollectionRun.objects.select_related("target", "organization")
        .prefetch_related("sources")
        .get(id=run_id)
    )
    if not run.target.allowed:
        run.status = CollectionRun.Status.BLOCKED
        run.error_message = "Cible non autorisée"
        run.save(update_fields=["status", "error_message"])
        return {"status": "blocked"}

    run.status = CollectionRun.Status.RUNNING
    run.started_at = timezone.now()
    run.save(update_fields=["status", "started_at"])
    observation_ids = []

    try:
        kind, value = run.target.kind, run.target.value
        payloads = []

        if kind == CollectionTarget.Kind.DOMAIN:
            payloads.append(("RDAP", "https://rdap.org", json.dumps(rdap_domain(value), ensure_ascii=False, default=str)))
            # DNS results are generated by AfricaWatch's collector; do not invent
            # a provider URL for them.
            payloads.append(("DNS", "", json.dumps(dns_enrichment(value), ensure_ascii=False, default=str)))
            payloads.append(("Certificate Transparency", "https://crt.sh/", json.dumps(certificate_transparency(value), ensure_ascii=False, default=str)))
        elif kind == CollectionTarget.Kind.IP:
            payloads.append(("RDAP", "https://rdap.org", json.dumps(rdap_ip(value), ensure_ascii=False, default=str)))
        elif kind == CollectionTarget.Kind.URL:
            payloads.append(("Public web target", value, json.dumps(public_page(value), ensure_ascii=False, default=str)))
        elif kind == CollectionTarget.Kind.ONION:
            payloads.append(("Public onion target", value, json.dumps(public_page(value, onion=True), ensure_ascii=False, default=str)))
        elif kind == CollectionTarget.Kind.ORGANIZATION:
            from django.conf import settings
            articles = gdelt_news(value) if getattr(settings, "INTEL_ENABLE_GDELT", True) else []
            for article in articles:
                payloads.append(("GDELT", article.get("url", ""), json.dumps(article, ensure_ascii=False, default=str)))
        elif kind in {
            CollectionTarget.Kind.EMAIL,
            CollectionTarget.Kind.PHONE_PUBLIC,
            CollectionTarget.Kind.SOCIAL_PUBLIC,
            CollectionTarget.Kind.USERNAME_PUBLIC,
            CollectionTarget.Kind.EMAIL_DOMAIN,
        }:
            payloads.append(("Public identifier", "", f"Identifiant public institutionnel: {value}"))
        else:
            payloads.append(("Unconfigured public search", "", f"Collecte passive différée pour {kind}: source de recherche institutionnelle à configurer."))

        from django.conf import settings
        sources = list(
            run.sources.filter(is_active=True)[:getattr(settings, "INTEL_MAX_SOURCES_PER_RUN", 12)]
        )
        if not sources:
            raise ValueError("Au moins une source institutionnelle doit être attachée à la collecte")

        for label, source_url, body in payloads[:getattr(settings, "INTEL_MAX_OBSERVATIONS_PER_RUN", 100)]:
            observation, _ = save_observation(
                run,
                None,
                f"{label} — {value}",
                body,
                url=source_url,
                provider_label=label,
                acquisition_method="built_in_passive_collector",
            )
            observation_ids.append(observation.id.hex)

        # Configured RSS and public API sources are recorded as the actual source
        # that supplied the content.
        for source in sources:
            try:
                if source.kind == CollectionSource.Kind.RSS and "{target}" not in source.url:
                    for entry in rss_entries(source.url, limit=25):
                        body = json.dumps(entry, ensure_ascii=False)
                        observation, _ = save_observation(
                            run,
                            source,
                            entry.get("title") or source.name,
                            body,
                            url=entry.get("url", ""),
                            raw=entry,
                            provider_label=source.name,
                            acquisition_method="configured_rss",
                        )
                        observation_ids.append(observation.id.hex)
                elif source.kind == CollectionSource.Kind.PUBLIC_API and "{target}" not in source.url:
                    snapshot = public_api_snapshot(source.url)
                    body = json.dumps(snapshot, ensure_ascii=False, default=str)
                    observation, _ = save_observation(
                        run,
                        source,
                        source.name,
                        body,
                        url=source.url,
                        raw=snapshot,
                        provider_label=source.name,
                        acquisition_method="configured_public_api",
                    )
                    observation_ids.append(observation.id.hex)
            except Exception:
                logger.exception("Configured source collection failed for source_id=%s", source.id)
                continue

        # Public-source templates target a public page without authentication.
        for source in sources:
            if "{target}" not in source.url or source.kind == CollectionSource.Kind.RDAP:
                continue
            target_url = source.url.replace("{target}", quote(value, safe=""))
            is_onion = source.kind == CollectionSource.Kind.ONION or ".onion" in (urlparse(target_url).hostname or "")
            try:
                page = public_page(target_url, onion=is_onion)
                observation, _ = save_observation(
                    run,
                    source,
                    page.get("title") or f"{source.name} — {value}",
                    page.get("body_preview", ""),
                    url=target_url,
                    raw=page,
                    provider_label=source.name,
                    acquisition_method="configured_public_web_template",
                )
                observation_ids.append(observation.id.hex)
            except Exception:
                logger.exception("Public source template failed for source_id=%s", source.id)
                continue

        # Optional reputation enrichment is passive. Each enrichment provider is
        # named explicitly; the first configured source is never used as a proxy.
        if kind in {CollectionTarget.Kind.IP, CollectionTarget.Kind.DOMAIN}:
            for label, provider_url, body in provider_enrichment(kind, value):
                observation, _ = save_observation(
                    run,
                    None,
                    f"{label} — {value}",
                    body,
                    url=provider_url,
                    provider_label=label,
                    acquisition_method="passive_reputation_enrichment",
                )
                observation_ids.append(observation.id.hex)

        _correlate_observations(run, observation_ids)
        manifest = build_run_manifest(run, generated_by=run.requested_by)
        run.status = CollectionRun.Status.COMPLETED
        run.completed_at = timezone.now()
        run.result_summary = {
            "observations": len(observation_ids),
            "evidence_records": manifest.evidence_count if manifest else 0,
            "evidence_root_hash": manifest.root_hash if manifest else "",
            "target": run.target.value,
            "mode": run.mode,
            "limitations": [
                "collecte passive; pas de connexion à des comptes privés",
                "les attributs personnels ne sont pas enrichis automatiquement",
                "les relations partagées par IOC ne prouvent pas à elles seules une attribution ou une campagne commune",
            ],
        }
        run.evidence_root_hash = manifest.root_hash if manifest else ""
        run.save(update_fields=["status", "completed_at", "result_summary", "evidence_root_hash"])
        return run.result_summary

    except Exception as exc:
        # Preserve a verifiable manifest for partial evidence before reporting the
        # collection failure. A manifest failure must not hide the original error.
        try:
            manifest = build_run_manifest(run, generated_by=run.requested_by)
            if manifest:
                run.evidence_root_hash = manifest.root_hash
        except Exception:
            logger.exception("Unable to create partial evidence manifest for run_id=%s", run.id)
        run.status = CollectionRun.Status.FAILED
        run.error_message = str(exc)[:4000]
        run.completed_at = timezone.now()
        run.save(update_fields=["status", "error_message", "completed_at", "evidence_root_hash"])
        raise


def _source_origin_key(observation) -> str:
    if observation.source_id:
        return f"source:{observation.source_id}"
    return f"provider:{(observation.source_label or 'unknown').strip().casefold()}"


def _correlate_observations(run, observation_ids):
    """Create only explicit shared-IOC relations; language equality is not evidence."""
    rows = list(
        IntelligenceObservation.objects.filter(
            id__in=set(observation_ids),
            organization=run.organization,
        ).select_related("source")
    )
    row_ids = [row.id for row in rows]

    # The acquisition ledger is authoritative for provenance because a
    # deduplicated analytical observation can have been acquired by more than
    # one configured source/provider over time.
    origins_by_observation = {row.id: set() for row in rows}
    evidence_rows = EvidenceRecord.objects.filter(
        organization=run.organization,
        observation_id__in=row_ids,
    ).values_list("observation_id", "source_id", "source_label")
    for observation_id, source_id, source_label in evidence_rows:
        origin = f"source:{source_id}" if source_id else f"provider:{(source_label or 'unknown').strip().casefold()}"
        origins_by_observation[observation_id].add(origin)

    # Legacy observations that predate the Evidence Ledger remain correlatable.
    for row in rows:
        if not origins_by_observation[row.id]:
            origins_by_observation[row.id].add(_source_origin_key(row))

    for index, left in enumerate(rows):
        left_iocs = {
            str(item.get("value", "")).strip().casefold()
            for item in (left.iocs or [])
            if item.get("value")
        }
        if not left_iocs:
            continue

        for right in rows[index + 1:]:
            right_iocs = {
                str(item.get("value", "")).strip().casefold()
                for item in (right.iocs or [])
                if item.get("value")
            }
            shared = left_iocs & right_iocs
            if not shared:
                continue

            weight = min(1.0, 0.45 + 0.15 * len(shared))
            IntelligenceRelation.objects.get_or_create(
                organization=run.organization,
                left=left,
                right=right,
                relation_type="shared_ioc",
                defaults={
                    "weight": weight,
                    "evidence": {"shared_iocs": sorted(shared)[:20]},
                },
            )

    # Count distinct acquisition origins attached to related observations,
    # excluding every origin already attached to the current observation.
    for row in rows:
        relations = IntelligenceRelation.objects.filter(organization=run.organization).filter(
            Q(left=row) | Q(right=row)
        ).values_list("left_id", "right_id")
        other_origins = set()
        own_origins = origins_by_observation[row.id]
        for left_id, right_id in relations:
            other_id = right_id if left_id == row.id else left_id
            other_origins.update(origins_by_observation.get(other_id, set()))
        corroboration = len(other_origins - own_origins)
        if row.corroboration_count != corroboration:
            row.corroboration_count = corroboration
            row.save(update_fields=["corroboration_count", "updated_at"])
